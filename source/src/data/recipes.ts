export const RECIPES: Recipe[] = [...BASE_RECIPES, ...MORE_RECIPES, ...ASIAN_RECIPES, ...SOUP_RECIPES, ...LIGHT_RECIPES, ...MEAL_RECIPES];

const BUILT_IN = RECIPES.length;
let appliedList: unknown;
let appliedItems: unknown;
/** Puts the family's own recipes (and the shop items they need) into the recipe book. Safe to call on every render. */
export function applyCustomRecipes(list: Recipe[] | undefined, items: AppState['customItems']) {
  if (appliedList === list && appliedItems === items) return;
  appliedList = list;
  appliedItems = items;
  RECIPES.length = BUILT_IN;
  RECIPES.push(...(list ?? []));
  for (const [k, v] of Object.entries(items ?? {})) if (!CATALOGUE[k]) CATALOGUE[k] = v as StoreItem;
}

export const recipeById = (id: string) => RECIPES.find((r) => r.id === id)!;
